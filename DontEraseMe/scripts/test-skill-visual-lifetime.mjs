import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const dir=await mkdtemp(join(tmpdir(),'skill-effects-'));
const outfile=join(dir,'fixture.mjs');
await build({stdin:{contents:`
export { Entity } from './src/core/Entity';
export { Transform } from './src/components/Transform';
export { EnemyBehavior } from './src/components/EnemyBehavior';
export { SkillVisual } from './src/components/SkillVisual';
export { ParticleSystem } from './src/systems/ParticleSystem';
export { skillVfx } from './src/art/SkillVfx';
`,resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',outfile});
const m=await import(pathToFileURL(outfile));
const system=new m.ParticleSystem();
const enemy=new m.Entity();const pos=enemy.addComponent(new m.Transform(20,30));
const behavior=enemy.addComponent(new m.EnemyBehavior('chaser'));behavior.frozenFrames=100;
const pin=m.skillVfx(20,30,'thumbtack',22,'#d6b07a',120);
pin.getComponent(m.SkillVisual).target=enemy;system.addEntity(pin);
pos.x=45;pos.y=60;system.update(1/60);
assert.equal(pin.getComponent(m.Transform).x,45);assert.equal(pin.getComponent(m.Transform).y,60);
behavior.frozenFrames=0;system.update(1/60);assert.equal(pin.active,false,'pin disappears when freeze ends');
const pin2=m.skillVfx(20,30,'thumbtack',22,'#d6b07a',120);pin2.getComponent(m.SkillVisual).target=enemy;
behavior.frozenFrames=10;system.addEntity(pin2);enemy.active=false;system.update(1/60);
assert.equal(pin2.active,false,'pin disappears with defeated target');
console.log('PASS: pin follows its target and is removed on death or thaw.');
