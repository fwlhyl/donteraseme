// Isolated browser context: do not touch the player's saved profile.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const path = process.env.PLAYWRIGHT_MODULE_PATH;
const { chromium } = path ? await import(pathToFileURL(path).href) : await import('playwright');
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
    await page.goto(process.env.GAME_URL || 'http://127.0.0.1:5173/index.html');
    await page.waitForFunction(() => !!window.gameInstance);
    await page.evaluate(async () => {
        const { PlayerProfile } = await import('/src/core/PlayerProfile.ts');
        PlayerProfile.save({ ...PlayerProfile.load(), coins: 2000 });
    });
    await page.locator('#create-mode-btn').click();
    assert.equal(await page.locator('.char-card').count(), 8);
    assert.equal(await page.locator('.weap-card').count(), 12);
    assert.equal(await page.locator('.char-card').nth(0).getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('.weap-card').nth(0).getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#start-run-btn').isEnabled(), true);
    await page.screenshot({ path: 'E:/Temp/loadout-layout.png' });
    await page.locator('.char-card').nth(1).click();
    assert.equal(await page.locator('#start-run-btn').isEnabled(), false);
    await page.locator('#unlock-character-btn').click();
    assert.equal(await page.locator('.char-card').nth(1).getAttribute('aria-pressed'), 'true', 'purchase retains character selection');
    await page.locator('.weap-card').nth(3).click();
    assert.equal(await page.locator('#start-run-btn').isEnabled(), false);
    await page.locator('#unlock-weapon-btn').click();
    assert.equal(await page.locator('.weap-card').nth(3).getAttribute('aria-pressed'), 'true', 'purchase retains weapon selection');
    assert.equal(await page.locator('#start-run-btn').isEnabled(), true);
    const data = await page.evaluate(() => JSON.parse(localStorage.getItem('dont_erase_me_player_profile_v1')));
    assert.equal(data.coins, 900); assert(data.unlockedCharacterIds.includes('graffiti')); assert(data.unlockedWeaponIds.includes(3));
    await page.locator('#back-to-menu-btn').click();
    await page.locator('#create-mode-btn').click();
    assert.equal(await page.locator('.char-card').nth(0).getAttribute('aria-pressed'), 'true', 'new entry resets character');
    assert.equal(await page.locator('.weap-card').nth(0).getAttribute('aria-pressed'), 'true', 'new entry resets weapon');
    await page.locator('#start-run-btn').click();
    await page.waitForFunction(() => window.gameInstance.state === 1);
    assert.equal(await page.locator('#selection-screen').isVisible(), false);
    await page.evaluate(() => { window.gameInstance.stop(); window.gameInstance.state = 0; window.gameInstance.showSelectionScreen('defense'); });
    assert.equal(await page.locator('.char-card').nth(0).getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('.weap-card').nth(0).getAttribute('aria-pressed'), 'true');
    await page.locator('.char-card').nth(1).click();
    await page.locator('#start-run-btn').click();
    assert.equal(await page.locator('#defense-artwork-overlay').isVisible(), true, 'guard artwork chooser opens separately');
    await page.locator('#defense-art-back').click();
    assert.equal(await page.locator('#selection-screen').isVisible(), true);
    assert.equal(await page.locator('.char-card').nth(1).getAttribute('aria-pressed'), 'true', 'back from guard chooser preserves selection');
    await page.setViewportSize({ width: 640, height: 720 });
    await page.reload();
    await page.waitForFunction(() => !!window.gameInstance);
    await page.evaluate(() => window.gameInstance.showSelectionScreen('defense'));
    await page.screenshot({ path: 'E:/Temp/loadout-layout-narrow.png' });
    assert.equal(await page.locator('#back-to-menu-btn').isVisible(), true);
    assert.equal(await page.locator('#start-run-btn').isVisible(), true);
    assert.deepEqual(errors, []);
    console.log('PASS: defaults, selection, purchases, persistence, mode change, start and narrow layout.');
} finally { await context.close(); await browser.close(); }
